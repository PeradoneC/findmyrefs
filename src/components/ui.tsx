export function DataLabel({ isDemo, providerName }: { isDemo: boolean; providerName?: string }) {
  return isDemo ? (
    <span
      className="badge badge-demo"
      title="Sample results generated by the mock provider. Not real images."
    >
      Demo data
    </span>
  ) : (
    <span className="badge badge-live" title="Results come from a live search provider.">
      Live{providerName ? `: ${providerName}` : ""}
    </span>
  );
}

