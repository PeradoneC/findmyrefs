export function ErrorBanner({
  message,
  onRetry,
  onDismiss,
}: {
  message: string;
  onRetry?: () => void;
  onDismiss?: () => void;
}) {
  return (
    <div className="banner banner-error" role="alert">
      <p style={{ flex: 1 }}>{message}</p>
      {onRetry && (
        <button type="button" className="btn btn-sm" onClick={onRetry}>
          Retry
        </button>
      )}
      {onDismiss && (
        <button
          type="button"
          className="btn btn-sm btn-ghost"
          onClick={onDismiss}
          aria-label="Dismiss error"
        >
          Dismiss
        </button>
      )}
    </div>
  );
}

export function Banner({
  kind,
  children,
}: {
  kind: "info" | "warn" | "demo";
  children: ReactNode;
}) {
  return (
    <div className={`banner banner-${kind}`} role={kind === "warn" ? "status" : undefined}>
      <div style={{ flex: 1 }}>{children}</div>
    </div>
  );
}

